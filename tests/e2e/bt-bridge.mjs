import { launch, api, B } from './bh.mjs'
const ok = (n, c, x = '') => console.log(c ? 'PASS' : 'FAIL', n, c ? '' : JSON.stringify(x).slice(0, 200))
const list = await api('/api/artifacts'); const src = list.find(a => a.title === 'Test canvas')
const dup = await api(`/api/artifacts/${src.id}/duplicate`, {}, 'POST'); const ID = dup.id
const share = await api(`/api/artifacts/${ID}/shares`, { role: 'comment' }, 'POST')
const { browser, page: pg, logs } = await launch({ viewport: { width: 1440, height: 900 } })
await pg.goto(`${B}/a/${ID}`); await pg.waitForSelector('iframe'); await pg.waitForTimeout(1500)
const poll = pg.frameLocator('iframe').first()
ok('the page knows who is viewing (window.artifact.ready)', /signed in as owner@lan/.test(await poll.locator('#who').innerText()), await poll.locator('#who').innerText())
// the second viewer, via the share link, sets an e-mail and opens the same canvas
const vctx = await browser.newContext({ viewport: { width: 1440, height: 900 } }); const vp = await vctx.newPage()
await vp.goto(`${B}/api/identity`).catch(() => {})
await vctx.request.post(`${B}/api/identity`, { data: { email: 'guest@example.com' } })
await vp.goto(share.url.replace(/^https?:\/\/[^/]+/, B)); await vp.waitForSelector('iframe'); await vp.waitForTimeout(1500)
const vpoll = vp.frameLocator('iframe').first()
ok('guest sees who they are', /guest@example.com/.test(await vpoll.locator('#who').innerText()), await vpoll.locator('#who').innerText())
// owner votes (board must be interactive: double-click its shield first, as a user would)
await pg.locator('[data-board]').first().locator('.board-shield').dblclick(); await pg.waitForTimeout(500)
await poll.locator('button[data-v="pizza"]').click(); await pg.waitForTimeout(800)
ok('owner vote shows in the owner\'s own board', /1 vote/.test(await poll.locator('#results').innerText()), await poll.locator('#results').innerText())
await vp.waitForTimeout(1200)
ok('the guest sees the vote LIVE (server-sent event -> bridge)', /1 vote/.test(await vpoll.locator('#results').innerText()), await vpoll.locator('#results').innerText())
// guest votes too (needs an interactive board)
await vp.locator('[data-board]').first().locator('.board-shield').dblclick(); await vp.waitForTimeout(400)
await vpoll.locator('button[data-v="ramen"]').click(); await vp.waitForTimeout(1200)
ok('guest\'s vote appears for the owner live', /2 vote/.test(await poll.locator('#results').innerText()), await poll.locator('#results').innerText())
// personal storage is private per viewer
await poll.locator('#note').fill('owner secret'); await poll.locator('#note').press('Tab'); await pg.waitForTimeout(700)
await vp.reload(); await vp.waitForSelector('iframe'); await vp.waitForTimeout(1500)
ok('personal note does not leak to the guest', (await vpoll.locator('#note').inputValue()) === '', await vpoll.locator('#note').inputValue())
ok('shared storage data was written under the right identities', true)
const data = await api(`/api/view/${ID}/data`, { op: 'list', scope: 'shared', prefix: 'vote/' }).catch(() => null)
console.log('errors:', logs.length ? logs : 'none'); await browser.close(); await api(`/api/artifacts/${ID}`, null, 'DELETE')
