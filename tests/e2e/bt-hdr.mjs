import { launch, B } from './bh.mjs'
const { browser, page: pg } = await launch({ viewport: { width: 1500, height: 900 } })
const ok = (n, c) => console.log(c ? 'PASS' : 'FAIL', n)
await pg.goto(`${B}/a/389e7acf-2575-492b-85cf-ae66e51a0c8d`); await pg.waitForSelector('iframe'); await pg.waitForTimeout(2500)
await pg.getByRole('button', { name: /^Comments/ }).click(); await pg.waitForTimeout(400)
ok('comments sidebar opens', await pg.locator('aside.side').isVisible())
await pg.getByRole('button', { name: 'Comment', exact: true }).click(); await pg.waitForTimeout(300)
ok('comment mode on', await pg.getByText('Click anything on the page to comment on it').isVisible())
await pg.getByRole('button', { name: 'Done commenting' }).click()
await pg.getByRole('button', { name: 'Share' }).click(); await pg.waitForTimeout(500)
ok('share popover', await pg.getByText('New comment link').isVisible())
await pg.keyboard.press('Escape')
await pg.locator('header.bar').getByRole('button', { name: 'Present' }).click(); await pg.waitForTimeout(800)
ok('present hides header', !(await pg.locator('header.bar').isVisible()))
await browser.close()
