import { launch, B } from './bh.mjs'
// Viewer header: the View / Edit / Review mode switch replaced the separate Comment and Done buttons.
// ARTIFACT=<id> picks the artifact to open (default: the original fixture).
const { browser, page: pg } = await launch({ viewport: { width: 1500, height: 900 } })
const ok = (n, c) => console.log(c ? 'PASS' : 'FAIL', n)
const mode = (name) => pg.getByRole('button', { name, exact: true }).first()
await pg.goto(`${B}/a/${process.env.ARTIFACT ?? '389e7acf-2575-492b-85cf-ae66e51a0c8d'}`); await pg.waitForSelector('iframe'); await pg.waitForTimeout(2500)
ok('mode switch shows View, Edit and Review', (await mode('View').count()) === 1 && (await mode('Edit').count()) === 1 && (await mode('Review').count()) === 1)
await mode('Review').click(); await pg.waitForTimeout(400)
ok('review opens the comments sidebar', await pg.locator('aside.side').isVisible())
ok('review turns comment mode on', await pg.getByText('Click anything on the page to comment on it').isVisible())
ok('review is the pressed mode', (await mode('Review').getAttribute('aria-pressed')) === 'true')
await mode('View').click(); await pg.waitForTimeout(300)
ok('view turns comment mode off', !(await pg.getByText('Click anything on the page to comment on it').isVisible()))
ok('view is the pressed mode', (await mode('View').getAttribute('aria-pressed')) === 'true')
await pg.getByRole('button', { name: 'Share' }).click(); await pg.waitForTimeout(500)
ok('share popover', await pg.getByText('New comment link').isVisible())
await pg.keyboard.press('Escape')
await pg.locator('header.bar').getByRole('button', { name: 'Present' }).click(); await pg.waitForTimeout(800)
ok('present hides header', !(await pg.locator('header.bar').isVisible()))
await browser.close()
