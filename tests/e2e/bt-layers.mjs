import { launch, api, B } from './bh.mjs'
const list = await api('/api/artifacts')
const src = list.find(a => a.title === 'Test canvas')
const id = (await api(`/api/artifacts/${src.id}/duplicate`, {}, 'POST')).id
const { browser, page: pg } = await launch({ viewport: { width: 1500, height: 920 } })
const ok = (n, c, x = '') => console.log(c ? 'PASS' : 'FAIL', n, c ? '' : x)
await pg.goto(`${B}/a/${id}`); await pg.waitForSelector('iframe'); await pg.waitForTimeout(900)
await pg.click('button:has-text("Edit")'); await pg.waitForTimeout(1500)
const tree = pg.locator('ul[aria-label="Canvas layers"]')
ok('canvas layers visible', await tree.isVisible())
const rows = await tree.locator('.row.board').count()
const nb = await pg.locator('[data-board]').count()
ok('all boards listed', rows === nb && rows > 1, `${rows} vs ${nb}`)
await tree.locator('.row.board').first().click(); await pg.waitForTimeout(300)
ok('board row selected', await tree.locator('.row.board.sel').count() === 1)
const kids = await tree.locator('ul.kids .row').count()
ok('board expands into elements', kids > 0, String(kids))
await tree.locator('ul.kids .row').first().click(); await pg.waitForTimeout(1500)
ok('element click focuses board', await pg.locator('.focusbar').count() > 0)
await pg.screenshot({ path: 'layers-1.png' })
await browser.close()
