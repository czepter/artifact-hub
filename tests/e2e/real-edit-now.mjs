import { launch, api, B } from './bh.mjs'
const list = await api('/api/artifacts')
const single = list.find(a => a.title === 'Single page')
const { browser, page, logs } = await launch({ viewport: { width: 1440, height: 900 } })
await page.goto(`${B}/a/${single.id}`)
await page.waitForSelector('iframe')
await page.waitForTimeout(800)
await page.click('button:has-text("Edit")')
await page.waitForTimeout(600)
// add an image via the palette (click)
await page.click('button:has-text("Image")')
await page.waitForTimeout(600)
await page.screenshot({ path: 'now-1.png' })
console.log('errors:', logs.length ? logs : 'none')
await browser.close()
